import assert from 'node:assert/strict';
import { brazilDate, inPeriod, periodRange, shiftPeriod } from '../src/lib/financialPeriod';
assert.deepEqual(periodRange('2026-08-30','day'), {start:'2026-08-30',end:'2026-08-30'});
assert.deepEqual(periodRange('2026-08-30','week'), {start:'2026-08-24',end:'2026-08-30'});
assert.deepEqual(periodRange('2026-08-31','week'), {start:'2026-08-31',end:'2026-09-06'});
assert.deepEqual(periodRange('2028-02-15','month'), {start:'2028-02-01',end:'2028-02-29'});
assert.deepEqual(periodRange('2026-12-31','week'), {start:'2026-12-28',end:'2027-01-03'});
assert.equal(shiftPeriod('2026-01-31','month',1),'2026-02-01');
assert.equal(shiftPeriod('2026-01-01','month',-1),'2025-12-01');
assert.equal(shiftPeriod('2026-08-30','week',-1),'2026-08-23');
assert.equal(brazilDate('2026-08-31T02:59:59Z'),'2026-08-30');
assert.equal(brazilDate('2026-08-31T03:00:00Z'),'2026-08-31');
assert.equal(brazilDate('2026-08-31'),'2026-08-31');
const month=periodRange('2026-08-30','month');
assert.equal(inPeriod('2026-09-01T02:59:59Z',month),true);
assert.equal(inPeriod('2026-09-01T03:00:00Z',month),false);
assert.equal(inPeriod('2026-08-01',month),true);
assert.equal(inPeriod('2026-07-31',month),false);
assert.equal(inPeriod(null,month),false);
assert.equal(inPeriod('invalid',month),false);
assert.throws(()=>periodRange('2026-02-31','month'));
console.log('PASS: daily, Monday-to-Sunday weeks, leap month, year boundaries, period navigation and Brazil timezone');
